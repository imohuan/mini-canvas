/**
 * debugDocAssets —— 独立调试页 sdk.js 的正文模板（纯字符串，零逻辑）。
 * 为什么单独一个文件：这是「JS 里嵌 JS」的字符串，塞主文件会把引号转义搅成粥。
 * CONTEXT_URL 占位符 __CONTEXT_URL__ 由调用方替换。
 *
 * ## 这个页面住在**另一个源**上（2026-10-20 审查 S1）
 *
 * 调试产物不再由后台的 `/api/...` 以 text/html 回读，而是另起一个端口（`debugOrigin`）。
 * 于是这个页面读不到画布页的 localStorage、cookie，也调不了后台的管理接口 ——
 * 节点 HTML 里的任意脚本只能在调试源里折腾自己。
 *
 * 代价是**所有请求都跨源**，所以这里有两处跟着改：
 *
 *   1. 数据不再用 `fetch` 拉（会被 CORS 挡），改成动态 `<script src>` 重载 ——
 *      script 标签不受同源策略限制，加载完就重新执行那几个 window 赋值；
 *   2. 上传产物带 `x-task-token`（绑定本画布本节点的短时令牌，由宿主机签发）。
 *      这里**不碰管理令牌**：调试页是用户代码，管理令牌一旦落进它就等于全开。
 */
export const SDK_JS_TEMPLATE = [
"/* 由 mini-canvas 自动生成 —— 调试窗口的 CanvasUI 桥。 */",
"(function(){",
"  var CONTEXT_URL = \"__CONTEXT_URL__\";",
"  var seq = 0;",
"  var changeFns = [];",
  "  /* 往外报：调试页是独立窗口，宿主是 opener（跨源，只能 '*'）。 */",
"  function tell(msg){",
"    msg.__canvasUiDebug = 1;",
"    try { if (window.opener) window.opener.postMessage(msg, \"*\"); } catch (e) {}",
"  }",
  // 调宿主代发：与 save 同一条路（回包按 reqId 认，两个标记都认）。
  // 这里只发消息，真正的权限表在宿主那侧（与画布里的沙箱页共用一个白名单）。
  "  var hostSeq = 0, hostPending = {};",
  "  function hostCall(type, fields, opts){",
  "    opts = opts || {};",
  "    return new Promise(function(resolve, reject){",
  "      if (!window.opener) { reject(new Error(\"这个窗口不是从画布打开的，没法代发请求\")); return; }",
  "      var id = \"d\" + (++hostSeq);",
  "      hostPending[id] = { resolve: resolve, reject: reject, onEvent: opts.onEvent };",
  "      var msg = fields || {};",
  "      msg.type = type; msg.reqId = id;",
  "      tell(msg);",
  "    });",
  "  }",
  "  function settleHost(m){",
  "    var p = hostPending[m.reqId]; if (!p) return;",
  "    if (m.type === \"task-event\") { if (p.onEvent) p.onEvent(m.event || {}); return; }",
  "    delete hostPending[m.reqId];",
  "    if (m.ok === false) p.reject(new Error(m.error || \"宿主代发失败\"));",
  "    else p.resolve(m);",
  "  }",
  "  window.addEventListener(\"message\", function(e){",
  "    if (e.source !== window.opener) return;",
  "    var d = e.data; if (!d || !d.__canvasUi || !d.reqId) return;",
  "    settleHost(d);",
  "  });",
"  function collect(){ return { upstream: window.__CANVAS_UPSTREAM__ || [], inputs: window.__CANVAS_INPUTS__ || {} }; }",
"  function fireChange(){ var p = collect(); for (var i = 0; i < changeFns.length; i++) { try { changeFns[i](p); } catch (e) {} } }",
"  /* 数据靠 <script> 重载：调试页与后台跨源，fetch 会被 CORS 挡；script 不受限。 */",
"  function reloadContext(){",
"    var s = document.createElement(\"script\");",
"    var sep = CONTEXT_URL.indexOf(\"?\") >= 0 ? \"&\" : \"?\";",
"    /* 重载前后比一次数据：没变就不打扰界面（否则每 5 秒白重绘一次）。 */",
"    var before = JSON.stringify(collect());",
"    s.src = CONTEXT_URL + sep + \"t=\" + Date.now() + \"-\" + (++seq);",
"    s.async = true;",
"    s.onload = function(){",
"      if (s.parentNode) s.parentNode.removeChild(s);",
"      if (JSON.stringify(collect()) !== before) fireChange();",
"    };",
"    s.onerror = function(){",
"      if (s.parentNode) s.parentNode.removeChild(s);",
"      console.warn(\"[ui-debug-doc] 重新加载 context 失败（下次轮询再试）\", s.src);",
"    };",
"    (document.head || document.documentElement).appendChild(s);",
"  }",
"  reloadContext();",
"  setInterval(reloadContext, 5000);",
"  window.CanvasUI = {",
"    setInputs: function(params){",
"      var cur = window.__CANVAS_INPUTS__ || {};",
"      var next = {}; for (var k in cur) next[k] = cur[k];",
"      for (var k2 in (params || {})) next[k2] = params[k2];",
"      window.__CANVAS_INPUTS__ = next;",
"      tell({ type: \"state\", state: next });",
"      fireChange();",
"    },",
"    onChange: function(fn){ if (typeof fn === \"function\") changeFns.push(fn); },",
  /* 与画布里那份同名同形：调试页上跑的应该是同一段代码，不该因为换了个窗口就少方法。 */
  "    api: function(path, init){",
  "      init = init || {};",
  "      return hostCall(\"api\", {",
  "        path: String(path || \"\"),",
  "        method: String(init.method || \"GET\"),",
  "        headers: init.headers || {},",
  "        body: init.body == null ? null : init.body,",
  "      }).then(function(m){",
  "        var bytes = m.body instanceof ArrayBuffer ? m.body : new Uint8Array(m.body || []).buffer;",
  "        var hdrs = m.headers || {};",
  "        var text = null;",
  "        function textOf(){ return text == null ? (text = new TextDecoder().decode(bytes)) : text; }",
  "        return {",
  "          ok: m.status >= 200 && m.status < 300,",
  "          status: m.status,",
  "          headers: { get: function(k){ return hdrs[String(k).toLowerCase()] || null; } },",
  "          text: function(){ return Promise.resolve(textOf()); },",
  "          json: function(){ return Promise.resolve().then(function(){ return JSON.parse(textOf()); }); },",
  "          arrayBuffer: function(){ return Promise.resolve(bytes); },",
  "        };",
  "      });",
  "    },",
  "    task: function(name, methods, args, opts){",
  "      opts = opts || {};",
  "      var wantEvents = !!(opts.onLog || opts.onProgress) && opts.wait !== true;",
  "      return hostCall(\"task\", {",
  "        name: String(name || \"\"), methods: String(methods || \"\"), args: args || [],",
  "        wait: opts.wait === true, subscribe: wantEvents,",
  "      }, { onEvent: function(ev){",
  "        if (ev.type === \"log\" && opts.onLog) opts.onLog(ev.line);",
  "        else if (ev.type === \"progress\" && opts.onProgress) opts.onProgress(ev.value);",
  "      } }).then(function(r){",
  "        if (r.ok === false) throw new Error(r.error || \"脚本跑失败了\");",
  "        return r;",
  "      });",
  "    },",
  "    cancel: function(runId){",
  "      return hostCall(\"task-cancel\", { runId: String(runId || \"\") }).catch(function(err){",
  "        return { ok: false, error: (err && err.message) || String(err) };",
  "      });",
  "    },",
"    save: function(data, name){",
"      var U = window.__CANVAS_UI__ || {};",
"      var token = U.debugToken || \"\";",
"      if (!token) {",
"        return Promise.reject(new Error(\"这个调试页没有写入令牌（可能已过期，或工具没签成）。请重跑 canvas_ui_build_debug_doc。\"));",
"      }",
"      var bytes = data;",
"      if (typeof data === \"string\") bytes = new Blob([data], { type: \"text/plain\" });",
"      var fname = String(name || \"out.png\");",
"      var withExt = /\\./.test(fname) ? fname : fname + \".png\";",
"      var url = (U.baseUrl || \"\") + \"/api/canvases/\" + encodeURIComponent(U.canvasId || \"default\")",
"        + \"/resources?slot=\" + encodeURIComponent(U.nodeId || \"\")",
"        + \"&name=\" + encodeURIComponent(withExt);",
"      /* 跨源写：带绑定本画布本节点的短时令牌（不是管理令牌）。 */",
"      return fetch(url, {",
"        method: \"POST\",",
"        headers: {",
"          \"content-type\": (bytes && bytes.type) || \"application/octet-stream\",",
"          \"x-task-token\": token,",
"        },",
"        body: bytes,",
"      })",
"        .then(function(r){",
"          return r.json().then(function(j){",
"            if (!r.ok) {",
              // 403 = 短令牌过期（或换了个槽位）：通知画布重新签一张，页面 5 秒内自动拿到新的。
"              if (r.status === 403) tell({ type: \"token-stale\" });",
"              throw new Error((j && j.error) || (\"保存产物失败 HTTP \" + r.status));",
"            }",
"            return j;",
"          });",
"        })",
"        .then(function(j){",
"          if (!j || !j.ok) throw new Error((j && j.error) || \"保存产物失败\");",
          // 宿主要靠这条把 uiOutputUrl / imageUrl 补进节点（产物本身在槽位里了）。
"          tell({ type: \"saved\", url: j.url, name: withExt, text: typeof data === \"string\" ? data : undefined });",
"          return j.url;",
"        });",
"    },",
"  };",
"})();",
].join('\n')

/**
 * 把 sdk 模板变成最终正文：替换 CONTEXT_URL 占位符。
 * 双重保险：模板里不该再出现第二个占位符（有就一并替换）。
 */
export function renderSdkJs(contextFileUrl: string): string {
  return SDK_JS_TEMPLATE.split('__CONTEXT_URL__').join(contextFileUrl)
}
