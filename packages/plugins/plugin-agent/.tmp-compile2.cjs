const fs = require('fs')
const { parse } = require('vue/compiler-sfc')
const { compileTemplate } = require('vue/compiler-sfc')
const src = fs.readFileSync(__dirname + '/src/ui/conversation/AgentMessageList.vue', 'utf8')
const { errors } = parse(src, { filename: 'AgentMessageList.vue' })
for (const e of errors) console.log('line', e.loc ? e.loc.start.line : '?', ':', e.message)
const { descriptor } = parse(src, { filename: 'AgentMessageList.vue' })
const r = compileTemplate({ source: descriptor.template.content, filename: 'AgentMessageList.vue', id: 'x' })
console.log('template errors:', r.errors.slice(0, 6).map((e) => (e && e.message) ? e.message : String(e)))
