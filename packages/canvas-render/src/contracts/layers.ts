/**
 * layers —— 画布**层叠带**的唯一事实源（z-index 单一出处）。
 *
 * 为什么要有这个文件：
 * 画布上「谁盖住谁」以前散在 6+ 个文件里各写一个数字（边 svg 1001、overlay 20、分组 -3、
 * 外壳 30/60/100000…）。这些数字各自看都合理，合起来却没人说得清整体层序，
 * 改一处很容易悄悄压掉另一处（2026-09-29 实测到「置顶连线盖住节点下控制栏」）。
 * 收成一张表后，「层序」只有一处可读、可测、可改。
 *
 * 怎么用：
 * - 只在这里定义数值；别处一律 `import { LAYERS }` 后取用，不得再写 z-index 字面量
 *   （历史散落数值的清单见 docs/plans/2026-09-29-canvas-z-layers.md §1.3）。
 * - 断言「相对顺序」而不是具体数字（见 __tests__/layers.test.ts）—— 数值可调，层序不可乱。
 *
 * 层序（自下而上）：
 *   分组容器 < 连线 < 节点 < 选中节点的连线 < 选中节点 < 置顶连线 < 临时菜单卡 < 节点上下控制栏
 *     < 画布浮层 < 外壳 UI < 模态
 *
 * 相邻两档留了间隔（而不是 1/2/3…）：中间要能插入新的层，不必再挪一遍所有数字。
 *
 * ⚠️ 两个层叠上下文事实（2026-09-29 实测，改动前必读）：
 * 1. `.vue-flow`（VueFlow 根）自身带 z-index，形成层叠上下文 —— 画布里的一切都关在里面，
 *    所以画布内任意大的 z 值都压不过作为它**兄弟**的 `.csurface-overlay`。
 * 2. `.vue-flow__node` 带 `transform`（定位用），**必然**形成层叠上下文 —— 节点内部的任何
 *    z-index 都出不去，越不过作为它**兄弟**的边 svg。这是 `nodeToolbar` 这一档能否成立的关键，
 *    详见 docs/plans/2026-09-29-canvas-z-layers.md §6。
 */

/**
 * 画布层叠带。语义见每个字段的注释；顺序由 __tests__/layers.test.ts 钉住。
 */
export const LAYERS = {
  /** 分组等容器型节点：垫在所有内容之下（嵌套再按深度细分，见 canvasHostCore） */
  groupBase: 50,
  /** 嵌套的内层分组：比外层分组高一点，但仍在连线之下 */
  groupNested: 60,
  /** 普通连线（VueFlow 每边一支 svg；默认在节点之下） */
  edge: 100,
  /** 普通节点卡片（所有未选中节点同一层） */
  node: 200,
  /** 选中节点的连线：抬到普通节点之上、选中节点之下（用户口述的层级语义：
   *  选中节点 > 其连线 > 其他节点/连线） */
  edgeSelected: 250,
  /** 选中节点：抬到普通节点之上，但**仍在置顶连线之下**（用户口述的层级语义） */
  nodeSelected: 300,
  /** 临时边（拖线占位、中间态）：要看得见，压在普通节点之上 */
  tempEdge: 380,
  /** 置顶连线（edgeOnTop=true）：压过所有节点，包括选中节点 */
  edgeTop: 400,
  /** 临时菜单卡（拖线落空白弹出的选类型卡）：恒在最上，避免被其他节点压住 */
  tempNode: 450,
  /**
   * 节点上/下控制栏（含编辑浮层）。**必须压过置顶连线**（用户口述：控制栏始终在最上面）。
   * 注意：要让这一条成立，控制栏不能住在带 transform 的节点里（见文件头 ⚠️ 第 2 条）。
   */
  nodeToolbar: 500,
  /** 画布级浮层槽（.csurface-overlay：小地图、对齐线、框选、批量连线临时线…） */
  overlay: 600,
  /** 应用级浮动（贴着外壳 UI 定位的浮层，如小地图）：在画布浮层之上、顶栏/底栏之下 */
  appFloat: 650,
  /** 外壳 UI（应用顶栏 / 底栏 / 状态条） */
  appChrome: 700,
  /** 屏幕级手势层（框选框 / 剪切刀光 / 批量连线临时线）：盖在外壳 UI 之上、模态之下。
   *  这些层挂在 document.body 上、只在自己那个手势期间存在，所以给独立一档，
   *  不与画布内的层级互相干扰。 */
  gesture: 900,
  /** 模态与菜单（沿用既有 100000 约定；见 ui-style-guide §2.8） */
  modal: 100000,
  /** 浮在模态之上的提示层（tooltip / 搜索浮层）：模态里也要能弹提示 */
  modalTop: 100001,
} as const

/** 层叠带取值类型（消费方用 `keyof typeof LAYERS` 索引） */
export type LayerName = keyof typeof LAYERS
